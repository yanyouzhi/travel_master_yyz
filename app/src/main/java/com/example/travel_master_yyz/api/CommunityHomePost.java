package com.example.travel_master_yyz.api;

public class CommunityHomePost {
    public String id;
    public String uid;
    public String photo;
    public String image;
    public String name;
    public String time;
    public String description;

    public String getTime() {
        return time;
    }

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getUid() {
        return uid;
    }

    public String getPhoto() {
        return photo;
    }

    public String getDescription() {
        return description;
    }

    public String getImage() {
        return image;
    }
}
